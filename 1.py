# ==========================================
# タイプ相性を計算
# ==========================================

def タイプ相性(技タイプ, 防御タイプ):

    倍率 = 1.0

    for タイプ in 防御タイプ:

        if 技タイプ in type_chart:

            倍率 = 倍率 * type_chart[技タイプ].get(
                タイプ,
                1
            )

    return 倍率


# ==========================================
# STAB
# ==========================================

def STAB計算(攻撃タイプ, 技タイプ):

    if 技タイプ in 攻撃タイプ:
        return 1.5

    return 1.0


# ==========================================
# 特性による技威力補正
# ==========================================

def 特性補正(特性, 技タイプ):

    if 特性 == "もうか" and 技タイプ == "ほのお":
        return 1.5

    if 特性 == "しんりょく" and 技タイプ == "くさ":
        return 1.5

    if 特性 == "げきりゅう" and 技タイプ == "みず":
        return 1.5

    return 1.0


